package signer

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"net/http"
	"net/url"
	"strings"
)

// 华为云 AK/SK 头签名（SDK-HMAC-SHA256）。
//
// 支持范围记录在此，并由 docs/验收/artifacts/tencent-huawei-signer/result.json 复述：
//
//   - method：GET / HEAD / POST / PUT / DELETE / PATCH / OPTIONS。
//   - 请求目标：绝对 URL，host 必须与登记 Binding 的 upstream origin 一致，路径必须落在登记前缀内。
//   - CanonicalURI：按 RFC3986 逐段百分号编码（保留 /），并以 “/” 结尾（华为云规范要求）。
//   - CanonicalQueryString：按 RFC3986 编码后按 key、value 升序；重复参数全部保留。
//   - CanonicalHeaders：host 与 x-sdk-date 必选，调用方可额外签名 content-type、content-md5；
//     有会话令牌时并入 x-security-token。其他 header 不在签名范围。
//   - HashedRequestPayload：只支持单个完整 body 的 SHA-256；
//     不支持 X-Sdk-Content-Sha256: UNSIGNED-PAYLOAD 之类的免签名 body。
//   - StringToSign：「SDK-HMAC-SHA256\n<X-Sdk-Date>\nHexEncode(SHA256(CanonicalRequest))」。
//
// 签名值只由 SK 派生，本包不写日志、不持久化签名材料。

const huaweiAlgorithm = "SDK-HMAC-SHA256"

// huaweiDateFormat 是华为云 X-Sdk-Date 的固定格式（UTC）。
const huaweiDateFormat = "20060102T150405Z"

var huaweiMethods = supportedMethods

// huaweiManagedHeaders 由签名器生成或从凭证取得，调用方不得覆盖。
var huaweiManagedHeaders = map[string]bool{
	"authorization":        true,
	"content-length":       true,
	"host":                 true,
	"x-sdk-date":           true,
	"x-security-token":     true,
	"x-sdk-content-sha256": true,
}

// huaweiAllowedHeaders 是除 host/x-sdk-date 外允许参与签名的调用方 header。
var huaweiAllowedHeaders = map[string]bool{
	"content-md5":  true,
	"content-type": true,
}

// SignHuawei 计算华为云 SDK-HMAC-SHA256 的 Authorization 头。
func SignHuawei(reg Registration, cred Credential, req Request) (*CloudResult, error) {
	target, err := prepareCloudRequest(reg, cred, req,
		huaweiMethods, "method is outside the supported set")
	if err != nil {
		return nil, err
	}
	uri, err := huaweiCanonicalURI(target.u)
	if err != nil {
		return nil, err
	}
	query, err := canonicalQuery(target.u.RawQuery)
	if err != nil {
		return nil, err
	}
	date := target.now.Format(huaweiDateFormat)
	canonicalHeaders, err := huaweiCanonicalHeaders(target, date, cred, req.Headers)
	if err != nil {
		return nil, err
	}
	names, block := canonicalHeaderBlock(canonicalHeaders)
	signedHeaders := strings.Join(names, ";")
	canonicalRequest := strings.Join([]string{
		target.method, uri, query, block, signedHeaders, target.payload,
	}, "\n")
	requestHash := sha256.Sum256([]byte(canonicalRequest))
	stringToSign := huaweiAlgorithm + "\n" + date + "\n" + hex.EncodeToString(requestHash[:])
	signature := hex.EncodeToString(hmacSHA256(cred.AccessSecret, stringToSign))

	out := http.Header{}
	out.Set("Authorization", fmt.Sprintf(
		"%s Access=%s, SignedHeaders=%s, Signature=%s",
		huaweiAlgorithm, cred.AccessID, signedHeaders, signature))
	out.Set("X-Sdk-Date", date)
	if cred.SessionToken != "" {
		out.Set("X-Security-Token", cred.SessionToken)
	}
	return &CloudResult{
		Headers:          out,
		SignedHeaders:    names,
		Timestamp:        date,
		CredentialScope:  target.region + "/" + target.service,
		Region:           target.region,
		Service:          target.service,
		canonicalRequest: canonicalRequest,
		stringToSign:     stringToSign,
		signature:        signature,
	}, nil
}

// huaweiCanonicalURI 逐段编码路径并补上结尾的 “/”，与华为云规范一致。
func huaweiCanonicalURI(u *url.URL) (string, error) {
	path := u.Path
	if path == "" {
		path = "/"
	}
	if !strings.HasPrefix(path, "/") {
		return "", errorf(CodeInvalidRequest, "url path must be absolute")
	}
	if hasControl(path) {
		return "", errorf(CodeInvalidRequest, "url path contains control characters")
	}
	segments := strings.Split(path, "/")
	encoded := make([]string, len(segments))
	for i, segment := range segments {
		encoded[i] = uriEncode(segment, true)
	}
	out := strings.Join(encoded, "/")
	if !strings.HasSuffix(out, "/") {
		out += "/"
	}
	return out, nil
}

// huaweiCanonicalHeaders 构造华为云的规范 header 块；值保留大小写，只折叠空白。
func huaweiCanonicalHeaders(target *cloudTarget, date string, cred Credential, extra http.Header) (map[string]string, error) {
	caller, err := cloudCallerHeaders(extra)
	if err != nil {
		return nil, err
	}
	headers := map[string]string{
		"host":       canonicalHost(target.u.Host, target.u.Scheme),
		"x-sdk-date": date,
	}
	for name, value := range caller {
		switch {
		case huaweiAllowedHeaders[name]:
			headers[name] = value
		case huaweiManagedHeaders[name]:
			return nil, errorf(CodeInvalidRequest, "header %q is generated by the signer", name)
		default:
			return nil, errorf(CodeUnsupported, "header %q is outside the supported SDK-HMAC-SHA256 signing set", name)
		}
	}
	if cred.SessionToken != "" {
		headers["x-security-token"] = cred.SessionToken
	}
	return headers, nil
}
